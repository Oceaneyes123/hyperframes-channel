def pstr(pts):
    return "M" + " L".join(f"{x} {y}" for x, y in pts)


def O(f0, f1, kind, target, payload=None, note=""):
    return (f0, f1, kind, target, payload, note)


def obj(i, slot, art=None, glyph=None, label="", job="", color=CLI, hidden=False, dim=False):
    d = dict(id=i, slot=slot, label=label, color=color, hidden=hidden, dim=dim)
    if art:
        d["art"] = art
    if glyph:
        d["glyph"] = glyph
    if job:
        d["job"] = job
    return d


def lbl(i, text, x, y, size=34, color=MUT, anchor="start", hidden=False, weight=700,
        family="mono"):
    return dict(id=i, text=text, x=x, y=y, size=size, color=color, anchor=anchor,
                hidden=hidden, weight=weight, family=family)


def chip(i, box, text, color=MUT, size=30, hidden=True, anchor="start"):
    return dict(id=i, box=box, text=text, color=color, size=size, hidden=hidden, anchor=anchor)


def out(i, y, text, glyph="circle-check", color=SUC, hidden=True, x=590, w=346, h=68):
    return dict(id=i, box=(x, y, w, h), text=text, glyph=glyph, color=color, hidden=hidden)


def glyph_el(i, name, x, y, size, color, hidden=True):
    return dict(id=i, glyph=name, x=x, y=y, size=size, color=color, hidden=hidden)


def route(i, pts, color="rule", dash=False, w=12, hidden=True):
    return dict(id=i, d=pstr(pts), color=color, dash=dash, w=w, hidden=hidden)


def tok(i, path, label, color=CLI, side="right", hidden=True):
    return dict(id=i, path=path, label=label, color=color, side=side, hidden=hidden)


def plate(ip="IP —", gw="GW —", dns="DNS —", note="NO ADDRESS", color=MUT, hidden=()):
    vals = [ip, gw, dns, note]
    colors = [MUT, MUT, MUT, color]
    out_ = []
    for k, (i, b, v, c) in enumerate(zip(PLATE_IDS, PLATE_BOXES, vals, colors)):
        out_.append(chip(i, b, v, c, size=34, hidden=(("p" + "ABCD"[k]) in hidden)))
    return out_


SCENES = []


def S(n, title, line, plan, mode, headline, **kw):
    sc = dict(n=n, title=title, line=line, plan=plan, mode=mode, headline=headline,
              objs=kw.get("objs", []), labels=kw.get("labels", []),
              chips=kw.get("chips", []) + kw.get("chips_extra", []), routes=kw.get("routes", []),
              tokens=kw.get("tokens", []), outcomes=kw.get("outcomes", []),
              glyphs=kw.get("glyphs", []), ops=kw.get("ops", []), cues=kw.get("cues", {}),
              note=kw.get("note"), notecolor=kw.get("notecolor", "muted"),
              hlsize=kw.get("hlsize", 88), beats_doc=kw["beats_doc"],
              objective=kw["objective"], dominant=kw["dominant"], icons=kw["icons"],
              objects=kw["objects"], text=kw["text"], anim=kw["anim"], begin=kw["begin"],
              end=kw["end"], next=kw["next"], hold=kw.get("hold", "none"),
              so=kw["so"], cut=kw.get("cut", "not inspected"),
              slots=sorted({o["slot"] for o in kw.get("objs", [])}))
    sc.update({k: v for k, v in kw.items() if k not in sc})   # carry per-scene extras
    SCENES.append(sc)


